"""
export_to_c.py
---------------
Writes the two generated headers used by the embedded engine:

  ecg_config.h  - sampling/detector constants, SOS filter coefficients
                  (single source of truth: stream_engine.py)
  ecg_model.h   - a trained scikit-learn RandomForestClassifier flattened
                  into const arrays + a tiny predict() function

No third-party converter is needed; the forest is just arrays of
(feature, threshold, left, right) plus leaf class-probabilities.

Threshold detail: scikit-learn casts inputs to float32 before comparing
(x <= threshold). We store each threshold as the largest float32 <= the
double threshold, so float32 comparisons give identical decisions.
"""

import os
import numpy as np

import stream_engine as se


def _num(v):
    return f"{float(v):.17g}"


def write_config_header(path, mains=se.MAINS_HZ):
    sos, zi = se.design_filters(se.FS, mains)
    rows = ",\n".join("    {" + ", ".join(_num(v) for v in r) + "}" for r in sos)
    zrows = ",\n".join("    {" + ", ".join(_num(v) for v in r) + "}" for r in zi)
    txt = f"""/* AUTO-GENERATED by export_to_c.py -- do not edit by hand. */
#ifndef ECG_CONFIG_H
#define ECG_CONFIG_H

#include <stdint.h>

#ifdef ECG_REAL_DOUBLE
typedef double ecg_real;      /* strict-parity / host testing */
#else
typedef float  ecg_real;      /* default for MCUs with a single-precision FPU */
#endif

#define ECG_FS          {se.FS}
#define ECG_BEFORE      {se.BEFORE}
#define ECG_AFTER       {se.AFTER}
#define ECG_WIN         {se.WIN}
#define ECG_MWI_W       {se.MWI_W}
#define ECG_REFRACT     {se.REFRACT}
#define ECG_WARM_N      {se.WARM_N}
#define ECG_BUF_LEN     {se.BUF_LEN}
#define ECG_DECAY_AFTER {se.DECAY_AFTER}
#define ECG_NORM_ALPHA  {_num(se.NORM_ALPHA)}
#define ECG_THR_FRAC    {_num(se.THR_FRAC)}
#define ECG_PEAK_ALPHA  {_num(se.PEAK_ALPHA)}
#define ECG_INIT_FRAC   {_num(se.INIT_FRAC)}
#define ECG_DECAY       {_num(se.DECAY)}
#define ECG_N_FEAT      {se.N_FEAT}
#define ECG_NSEC        {len(sos)}

/* Mains notch designed for {mains:g} Hz */
static const ecg_real ECG_SOS[ECG_NSEC][6] = {{
{rows}
}};

/* Steady-state initial filter state for a unit step */
static const ecg_real ECG_ZI[ECG_NSEC][2] = {{
{zrows}
}};

#endif /* ECG_CONFIG_H */
"""
    with open(path, "w") as f:
        f.write(txt)


def _floor_f32(t):
    """Largest float32 that is <= the double threshold t."""
    f = np.float32(t)
    if float(f) > t:
        f = np.nextafter(f, np.float32(-np.inf))
    return f


def write_model_header(path, model, feature_names=None):
    classes = [str(c) for c in model.classes_]
    assert all(len(c) == 1 for c in classes), "class labels must be single chars"
    nc = len(classes)

    feat, thr, left, right, roots, leaves = [], [], [], [], [], []
    for est in model.estimators_:
        t = est.tree_
        base = len(feat)
        roots.append(base)
        for i in range(t.node_count):
            if t.children_left[i] == -1:                     # leaf
                v = t.value[i, 0, :]
                v = v / v.sum()
                feat.append(-1)
                thr.append(0.0)
                left.append(len(leaves))                     # leaf index
                right.append(0)
                leaves.append(v)
            else:
                feat.append(int(t.feature[i]))
                thr.append(float(_floor_f32(t.threshold[i])))
                left.append(base + int(t.children_left[i]))
                right.append(base + int(t.children_right[i]))
    n_nodes, n_leaves = len(feat), len(leaves)
    assert n_nodes < 32767 and n_leaves < 32767, \
        "model too large for int16 indices: use fewer trees / smaller depth"

    flash = n_nodes * (1 + 4 + 2 + 2) + n_leaves * nc * 4 + len(roots) * 2
    arr = lambda xs, f: ", ".join(f(x) for x in xs)
    txt = f"""/* AUTO-GENERATED by export_to_c.py -- do not edit by hand.
 * RandomForest: {len(roots)} trees, {n_nodes} nodes, {n_leaves} leaves,
 * classes {classes}, ~{flash/1024:.1f} KiB of flash. */
#ifndef ECG_MODEL_H
#define ECG_MODEL_H

#include "ecg_config.h"

#define ECG_N_TREES   {len(roots)}
#define ECG_N_CLASSES {nc}

static const char ECG_CLASSES[ECG_N_CLASSES] = {{{", ".join("'%s'" % c for c in classes)}}};
{"/* features: " + ", ".join(feature_names) + " */" if feature_names else ""}

static const int16_t ECG_TREE_ROOT[ECG_N_TREES] = {{{arr(roots, str)}}};
static const int8_t  ECG_NODE_FEAT[{n_nodes}] = {{{arr(feat, str)}}};
static const float   ECG_NODE_THR[{n_nodes}] = {{{arr(thr, lambda v: repr(float(np.float32(v))) + "f")}}};
static const int16_t ECG_NODE_LEFT[{n_nodes}] = {{{arr(left, str)}}};
static const int16_t ECG_NODE_RIGHT[{n_nodes}] = {{{arr(right, str)}}};
static const float   ECG_LEAF_PROBA[{n_leaves}][ECG_N_CLASSES] = {{
{",\n".join("    {" + arr(v, lambda p: repr(float(np.float32(p))) + "f") + "}" for v in leaves)}
}};

/* Returns the predicted class index; *p_out = averaged class probability. */
static int ecg_model_predict(const ecg_real *x, float *p_out)
{{
    float acc[ECG_N_CLASSES];
    int c, t, best = 0;
    for (c = 0; c < ECG_N_CLASSES; c++) acc[c] = 0.0f;
    for (t = 0; t < ECG_N_TREES; t++) {{
        int i = ECG_TREE_ROOT[t];
        while (ECG_NODE_FEAT[i] >= 0) {{
            float xv = (float)x[ECG_NODE_FEAT[i]];
            i = (xv <= ECG_NODE_THR[i]) ? ECG_NODE_LEFT[i] : ECG_NODE_RIGHT[i];
        }}
        for (c = 0; c < ECG_N_CLASSES; c++)
            acc[c] += ECG_LEAF_PROBA[ECG_NODE_LEFT[i]][c];
    }}
    for (c = 1; c < ECG_N_CLASSES; c++)
        if (acc[c] > acc[best]) best = c;
    *p_out = acc[best] / (float)ECG_N_TREES;
    return best;
}}

#endif /* ECG_MODEL_H */
"""
    with open(path, "w") as f:
        f.write(txt)
    return {"trees": len(roots), "nodes": n_nodes, "leaves": n_leaves,
            "flash_kib": round(flash / 1024, 1)}


def export_all(model, out_dir, feature_names=None, mains=se.MAINS_HZ):
    os.makedirs(out_dir, exist_ok=True)
    write_config_header(os.path.join(out_dir, "ecg_config.h"), mains)
    info = write_model_header(os.path.join(out_dir, "ecg_model.h"), model,
                              feature_names)
    print(f"Exported C headers to {out_dir}: {info}")
    return info
